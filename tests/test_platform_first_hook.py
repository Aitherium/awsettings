def _run(command: str, tool: str = "Bash", cwd: str | None = None) -> tuple[int, str, str]:
    payload = {"tool_name": tool, "tool_input": {"command": command}, "session_id": "t"}
    if cwd:
        payload["cwd"] = cwd
    out, err = io.StringIO(), io.StringIO()
    rc = platform_first.guard_main(io.StringIO(json.dumps(payload)), out, err)
    return rc, out.getvalue(), err.getvalue()


