def test_guard_main_in_process_is_fast():
    payload = json.dumps({"tool_name": "Bash", "tool_input": {"command": "rm -rf /c/x/lock"}})
    times = []
    for _ in range(200):
        start = time.perf_counter()
        platform_first.guard_main(io.StringIO(payload), io.StringIO(), io.StringIO())
        times.append((time.perf_counter() - start) * 1000.0)
    assert statistics.median(times) < 5.0


def test_cold_module_start_is_inside_the_hook_budget():
    """A fresh interpreter importing the guard and deciding one payload: the cost a
    console-script hook pays per matched call. Budget 100 ms on top of bare
    interpreter start (measured in the same run, so a slow host does not fail it)."""
    payload = json.dumps({"tool_name": "Bash", "tool_input": {"command": "rm -rf /c/x/lock"}})
    code = ("import sys; from awsettings import platform_first as p; "
            "sys.exit(p.guard_main())")

    import os
    import pathlib

    pkg_root = pathlib.Path(platform_first.__file__).resolve().parents[1]
    env = dict(os.environ, PYTHONPATH=str(pkg_root))

    # Fastest of several runs: the intrinsic cost; a loaded host only adds noise.
    def _fastest(args: list[str]) -> float:
        times = []
        for _ in range(9):
            start = time.perf_counter()
            subprocess.run(args, input=payload, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", check=False,
                           env=env)
            times.append((time.perf_counter() - start) * 1000.0)
        return min(times)

    floor = _fastest([sys.executable, "-c", "pass"])
    guard = _fastest([sys.executable, "-c", code])
    assert guard - floor < 100.0, f"guard {guard:.0f} ms vs interpreter floor {floor:.0f} ms"
