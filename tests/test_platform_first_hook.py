def test_pretooluse_group_is_installed_once_with_exec_form():
    out = hooks.plan({})
    groups = out["hooks"]["PreToolUse"]
    assert len(groups) == 1
    group = groups[0]
    assert group["matcher"] == "Bash|PowerShell"
    assert len(group["hooks"]) == 1
    entry = group["hooks"][0]
    assert entry["command"] == "awsettings-guard"
    assert entry["args"] == []
    assert entry["type"] == "command"
    # EXEC form: no shell string, no absolute path -> valid on every OS.
    assert "/" not in entry["command"] and "\\" not in entry["command"]
    assert entry.get(hooks.MARKER) is True


def test_plan_is_idempotent_twenty_times():
    settings: dict = {}
    for _ in range(20):
        settings = hooks.plan(settings)
    assert len(settings["hooks"]["PreToolUse"]) == 1
    assert len(settings["hooks"]["SessionStart"]) == 1
    assert len(settings["hooks"]["PostToolUse"]) == 1


def test_uninstall_removes_only_our_pre_tool_group():
    foreign = {
        "hooks": {
            "PreToolUse": [
                {"matcher": "Read", "hooks": [{"type": "command", "command": "theirs"}]}
            ],
        }
    }
    out = hooks.uninstall(hooks.plan(foreign))
    assert hooks.installed(out) == []
    cmds = [h["command"] for g in out["hooks"]["PreToolUse"] for h in g["hooks"]]
    assert cmds == ["theirs"]


def test_pretooluse_group_travels_via_portable_hooks():
    """The marker makes the guard portable: push carries it, every pull installs it."""
    portable = core.portable_hooks(hooks.plan({})["hooks"])
    assert "PreToolUse" in portable
    entry = portable["PreToolUse"][0]["hooks"][0]
    assert entry["command"] == "awsettings-guard"
    assert "SessionStart" in portable and "PostToolUse" in portable


